"""Concatenate src/ parts into the single-file game.

Writes two files:
  twinfang.html      the public build, from src/ only
  twinfang.dev.html  the developer build, src/ plus the parts in dev/ (git-ignored, never published)

Usage: python build.py
"""
import base64
import glob
import io
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "src")
dev = os.path.join(here, "dev")


def read(path):
    with io.open(path, encoding="utf-8") as f:
        return f.read()


def js_parts(folder):
    return [read(p).rstrip("\n") + "\n\n" for p in sorted(glob.glob(os.path.join(folder, "*.js")))]


def write(name, parts):
    with io.open(os.path.join(here, name), "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(parts))
    print("built %s from %d parts" % (name, len(parts)))


def samples_part():
    """src/samples/*.mp3 as one generated part: the game is opened from a file, where it cannot fetch side files,
    so the recordings travel inside it as base64. SMP.f holds the measured pitch of the tuned ones."""
    d = os.path.join(src, "samples")
    if not os.path.isdir(d):
        return ""
    idx = os.path.join(d, "index.json")
    tune = {k: v["f"] for k, v in json.load(io.open(idx, encoding="utf-8")).items()} if os.path.exists(idx) else {}
    rows = []
    for p in sorted(glob.glob(os.path.join(d, "*.mp3"))):
        with open(p, "rb") as f:
            rows.append("'%s':'%s'" % (os.path.basename(p)[:-4], base64.b64encode(f.read()).decode("ascii")))
    return ("// ===================== SAMPLES =====================\n"
            "// Generated by build.py from src/samples (credits in src/samples/CREDITS.md): short CC0 recordings as base64 MP3.\n"
            "const SMP={f:%s,d:{\n%s\n}};\n\n" % (json.dumps(tune, separators=(",", ":")), ",\n".join(rows)))


head = read(os.path.join(src, "00-head.html"))
tail = read(os.path.join(src, "99-tail.html"))
game = js_parts(src)
game.insert(1, samples_part())   # after 01-util.js, before the audio engine that uses it

write("twinfang.html", [head] + game + [tail])
dev_parts = js_parts(dev) if os.path.isdir(dev) else []
if dev_parts:
    write("twinfang.dev.html", [head.replace("<title>TWINFANG</title>", "<title>TWINFANG (dev)</title>")] + game + dev_parts + [tail])
